import string

import pytest
from hypothesis import given, example, strategies as st
from highway_toll import parse_plate, trip_cost, axle_class

# ---------------------------------------------------------------------------
# Fuzz tests: any text (or None) must either give a sane result or be rejected
# with ValueError. Any other exception (AttributeError, TypeError, ...) or an
# unhandled unpacking error is an input validation bug.
# ---------------------------------------------------------------------------

@given(st.text() | st.none())
@example(None)
@example("")
@example("KA-05-AB-1234")
@example("KA-05-AB")            # too few parts
@example("KA-05-AB-12-34")      # too many parts
@example("-٣--٤")               # non-ASCII digits, empty state
@example("KA--5-AB-1_0")        # negative district, underscore digits
def test_parse_plate_no_crash(s):
    try:
        state, district, number = parse_plate(s)
    except ValueError:
        return
    assert len(state) == 2 and state.isascii() and state.isalpha() and state.isupper()
    assert 0 <= district <= 99
    assert 0 <= number <= 9999


@given(st.text() | st.none())
@example(None)
@example("")
@example("x")
@example("3x150")
@example("3X150")
@example("-3x150")              # negative trips gave a negative toll
@example("3x-150")
@example("0x150")
@example("1x2x3")
@example(" 3 x 1_5 ")           # spaces and underscores accepted by int()
def test_trip_cost_no_crash(s):
    try:
        cost = trip_cost(s)
    except ValueError:
        return
    assert isinstance(cost, int)
    assert cost >= 0


@given(st.text() | st.none())
@example(None)
@example("")
@example("2")
@example("0")                   # used to be classified as 'truck'
@example("1")                   # used to be classified as 'truck'
@example("-7")                  # used to be classified as 'truck'
@example("999999")              # used to be classified as 'heavy'
@example("2.5")
@example("٣")                   # non-ASCII digit
def test_axle_class_no_crash(s):
    try:
        result = axle_class(s)
    except ValueError:
        return
    assert result in ('car', 'truck', 'heavy')
    assert 2 <= int(s) <= 20


# ---------------------------------------------------------------------------
# Valid inputs generated by Hypothesis must still be accepted and be correct.
# ---------------------------------------------------------------------------

letters = st.sampled_from(string.ascii_letters)

@given(
    st.text(letters, min_size=2, max_size=2),
    st.integers(0, 99),
    st.text(letters, min_size=1, max_size=3),
    st.integers(0, 9999),
)
def test_parse_plate_valid(state, district, series, number):
    plate = f"{state}-{district:02d}-{series}-{number:04d}"
    assert parse_plate(plate) == (state.upper(), district, number)


@given(st.integers(1, 999999), st.integers(0, 999999), st.sampled_from("xX"))
def test_trip_cost_valid(count, rate, sep):
    assert trip_cost(f"{count}{sep}{rate}") == count * rate


@given(st.integers(2, 20))
def test_axle_class_valid(n):
    expected = 'car' if n == 2 else 'truck' if n <= 4 else 'heavy'
    assert axle_class(str(n)) == expected


# ---------------------------------------------------------------------------
# Regression tests for the specific bugs the fuzzer exposed.
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("func", [parse_plate, trip_cost, axle_class])
@pytest.mark.parametrize("bad", [None, "", "   ", 5, "abc", "\x00"])
def test_bad_input_is_rejected_with_value_error(func, bad):
    with pytest.raises(ValueError):
        func(bad)


@pytest.mark.parametrize("bad", ["0", "1", "-7", "999999", "2.5", "+3", "٣"])
def test_axle_class_rejects_out_of_range(bad):
    with pytest.raises(ValueError):
        axle_class(bad)


@pytest.mark.parametrize("bad", ["-3x150", "3x-150", "0x150", "1x2x3", "3x", "x150", "1_0x5"])
def test_trip_cost_rejects_bad_numbers(bad):
    with pytest.raises(ValueError):
        trip_cost(bad)
